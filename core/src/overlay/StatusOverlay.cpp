bool renderText(const std::string& text, int scale, std::vector<std::uint8_t>& outRgba,
                std::uint32_t& outWidth, std::uint32_t& outHeight, std::string& error)
{
    outRgba.clear();
    outWidth = 0;
    outHeight = 0;
    if (scale < 1)
    {
        error = "scale must be >= 1";
        return false;
    }

    // Split into lines ('\n' breaks, '\r' is dropped).
    std::vector<std::string> lines;
    std::string current;
    for (const char c : text)
    {
        if (c == '\n')
        {
            lines.push_back(current);
            current.clear();
        }
        else if (c != '\r')
        {
            current.push_back(c);
        }
    }
    lines.push_back(current);

    size_t longest = 0;
    for (const auto& line : lines)
    {
        longest = std::max(longest, line.size());
    }
    if (lines.empty() || longest == 0)
    {
        return true; // nothing to draw
    }

    const int cellW = (kGlyphWidth + kCharGap) * scale;
    const int lineH = (kGlyphHeight + kLineGap) * scale;
    const std::uint32_t width = static_cast<std::uint32_t>(longest) * static_cast<std::uint32_t>(cellW);
    const std::uint32_t height = static_cast<std::uint32_t>(lines.size()) * static_cast<std::uint32_t>(lineH);

    outRgba.assign(static_cast<size_t>(width) * static_cast<size_t>(height) * 4u, 0);
    outWidth = width;
    outHeight = height;

    for (size_t lineIdx = 0; lineIdx < lines.size(); ++lineIdx)
    {
        const std::uint32_t baseY = static_cast<std::uint32_t>(lineIdx) * static_cast<std::uint32_t>(lineH);
        const std::string& line = lines[lineIdx];
        for (size_t col = 0; col < line.size(); ++col)
        {
            const Glyph* glyph = glyphFor(line[col]);
            const std::uint32_t baseX = static_cast<std::uint32_t>(col) * static_cast<std::uint32_t>(cellW);
            for (int r = 0; r < kGlyphHeight; ++r)
            {
                for (int cIdx = 0; cIdx < kGlyphWidth; ++cIdx)
                {
                    if (glyph->rows[r][cIdx] != '1')
                    {
                        continue;
                    }
                    // Fill the scale x scale block for this on-pixel.
                    for (int dy = 0; dy < scale; ++dy)
                    {
                        for (int dx = 0; dx < scale; ++dx)
                        {
                            const std::uint32_t x = baseX + static_cast<std::uint32_t>(cIdx) * scale +
                                                    static_cast<std::uint32_t>(dx);
                            const std::uint32_t y = baseY + static_cast<std::uint32_t>(r) * scale +
                                                    static_cast<std::uint32_t>(dy);
                            if (x >= width || y >= height)
                            {
                                continue;
                            }
                            std::uint8_t* px = outRgba.data() + (static_cast<size_t>(y) * width + x) * 4u;
                            px[0] = 255;
                            px[1] = 255;
                            px[2] = 255;
                            px[3] = 255;
                        }
                    }
                }
            }
        }
    }
    return true;
}

