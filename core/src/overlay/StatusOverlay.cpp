constexpr int kGlyphWidth = 8;
constexpr int kGlyphHeight = 11;
constexpr int kCharGap = 1;  // px between characters (at scale 1)
constexpr int kLineGap = 1;  // px between lines (at scale 1)

const Glyph* glyphFor(char c)
{
    const unsigned code = static_cast<unsigned char>(c);
    if (code < 32u || code > 126u)
    {
        return &kFont[0]; // blank
    }
    return &kFont[code - 32u];
}

